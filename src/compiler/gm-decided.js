// The reason the user gave for this creature's ability, or null.
export function gmDecided(actorName, abilityName) {
    const rows = BY_ABILITY.get(String(abilityName ?? "").trim());
    const name = String(actorName ?? "").trim();
    return rows?.find(([creature]) => name === creature || name.endsWith(` ${creature}`))?.[1] ?? null;
}
